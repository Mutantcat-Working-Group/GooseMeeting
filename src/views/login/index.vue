<template>
  <div class="login-container">
    <el-form ref="loginForm" :model="loginForm" :rules="loginRules" class="login-form" autocomplete="on" label-position="left">

      <div class="title-container">
        <h3 class="title">大鹅会议</h3>
        <p class="version">v{{ version }}</p>
      </div>

      <el-form-item v-if="desktop" class="server-field">
        <el-input v-model="serverUrl" aria-label="服务器地址" placeholder="https://会议服务器地址" prefix-icon="el-icon-link" @change="saveServer" />
      </el-form-item>

      <el-form-item prop="username">
        <span class="svg-container">
          <svg-icon icon-class="user" />
        </span>
        <el-input
          ref="username"
          v-model="loginForm.username"
          placeholder="用户名"
          name="username"
          type="text"
          tabindex="1"
          autocomplete="on"
        />
      </el-form-item>

      <el-tooltip v-model="capsTooltip" content="Caps lock is On" placement="right" manual>
        <el-form-item prop="password">
          <span class="svg-container">
            <svg-icon icon-class="password" />
          </span>
          <el-input
            :key="passwordType"
            ref="password"
            v-model="loginForm.password"
            :type="passwordType"
            placeholder="密码"
            name="password"
            tabindex="2"
            autocomplete="on"
            @keyup.native="checkCapslock"
            @blur="capsTooltip = false"
            @keyup.enter.native="handleLogin"
          />
          <span class="show-pwd" @click="showPwd">
            <svg-icon :icon-class="passwordType === 'password' ? 'eye' : 'eye-open'" />
          </span>
        </el-form-item>
      </el-tooltip>

      <el-button :loading="loading" type="primary" style="width:80%;margin-bottom:30px;" @click.native.prevent="handleLogin">登录</el-button>

      <el-button class="thirdparty-button" type="primary" @click="openRegister">
        注册
      </el-button>

    </el-form>

    <el-dialog width="500px" title="注册" :visible.sync="showDialog">
      <Register />
    </el-dialog>
  </div>
</template>

<script>
import Register from './components/Register'
import { getServerUrl, setServerUrl, isDesktop } from '@/utils/server'
import { version } from '../../../package.json'

export default {
  name: 'Login',
  components: { Register },
  data() {
    const validateUsername = (rule, value, callback) => {
      if (!value) {
        return callback(new Error('请输入用户名'))
      }
      var reg = /^[a-zA-Z]\w{4,15}$/
      if (!reg.test(value)) {
        return callback(new Error('字母开头，5-16字节，字母数字下划线组合'))
      }
      callback()
    }
    const validatePassword = (rule, value, callback) => {
      if (value === '') {
        callback(new Error('请输入密码'))
      } else {
        var reg = /^[\u0021-\u007E]{6,16}$/
        if (!reg.test(value)) {
          return callback(new Error('长度6-16'))
        }
        callback()
      }
    }
    return {
      desktop: isDesktop,
      version,
      serverUrl: isDesktop ? getServerUrl() : '',
      loginForm: {
        username: '',
        password: ''
      },
      loginRules: {
        username: [{ required: true, trigger: 'blur', validator: validateUsername }],
        password: [{ required: true, trigger: 'blur', validator: validatePassword }]
      },
      passwordType: 'password',
      capsTooltip: false,
      loading: false,
      showDialog: false,
      redirect: undefined,
      otherQuery: {}
    }
  },
  watch: {
    $route: {
      handler: function(route) {
        const query = route.query
        if (query) {
          this.redirect = query.redirect
          this.otherQuery = this.getOtherQuery(query)
        }
      },
      immediate: true
    }
  },
  created() {
    // window.addEventListener('storage', this.afterQRScan)
  },
  mounted() {
    if (this.loginForm.username === '') {
      this.$refs.username.focus()
    } else if (this.loginForm.password === '') {
      this.$refs.password.focus()
    }
  },
  destroyed() {
    // window.removeEventListener('storaconnect ge', this.afterQRScan)
  },
  methods: {
    saveServer() {
      if (!this.desktop) return true
      try {
        const previous = getServerUrl()
        const next = setServerUrl(this.serverUrl)
        this.serverUrl = next
        if (previous !== next) this.$store.dispatch('user/resetToken')
        return true
      } catch (error) {
        this.$message.error('请输入有效的 HTTP(S) 服务器地址，不要包含账号、参数或片段')
        return false
      }
    },
    openRegister() {
      if (this.saveServer()) this.showDialog = true
    },
    checkCapslock(e) {
      const { key } = e
      this.capsTooltip = key && key.length === 1 && (key >= 'A' && key <= 'Z')
    },
    showPwd() {
      if (this.passwordType === 'password') {
        this.passwordType = ''
      } else {
        this.passwordType = 'password'
      }
      this.$nextTick(() => {
        this.$refs.password.focus()
      })
    },
    handleLogin() {
      if (!this.saveServer()) return
      this.$refs.loginForm.validate(valid => {
        if (valid) {
          this.loading = true
          this.$store.dispatch('user/login', this.loginForm)
            .then(() => {
              this.$router.push({ path: this.redirect || '/', query: this.otherQuery })
              this.loading = false
            })
            .catch(() => {
              this.loading = false
            })
        } else {
          console.log('error submit!!')
          return false
        }
      })
    },
    getOtherQuery(query) {
      return Object.keys(query).reduce((acc, cur) => {
        if (cur !== 'redirect') {
          acc[cur] = query[cur]
        }
        return acc
      }, {})
    }
    // afterQRScan() {
    //   if (e.key === 'x-admin-oauth-code') {
    //     const code = getQueryObject(e.newValue)
    //     const codeMap = {
    //       wechat: 'code',
